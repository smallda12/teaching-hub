def 提示詞(畫面):
    return "%s %s %s %s" % (STYLE, 畫面, 版面, 禁止)


def 檔名(領域, 序):
    # 🛑 網站 assets 一律 ASCII 檔名（中文檔名在 GitHub Pages 上會出問題）
    代碼 = {"自然": "nature", "社會": "society", "數學": "math", "語文": "chinese",
          "健體": "pe", "綜合": "life", "藝文": "arts",
          "特需生活管理": "selfcare", "特需功能性動作訓練": "motor"}
    assert 領域 in 代碼, "領域 %s 還沒登記英文代碼" % 領域
    return "%s%02d" % (代碼[領域], 序)


def _驗出圖(路徑):
    """只擋明顯壞掉的圖；印的是量出來的值，不是常數。"""
    try:
        from PIL import Image, ImageStat
    except ImportError:
        return True, "（未安裝 Pillow，略過）"
    大小 = os.path.getsize(路徑)
    if 大小 < 150 * 1024:
        return False, "只有 %.1f KB" % (大小 / 1024)
    im = Image.open(路徑)
    if im.size != (1536, 1024):
        return False, "尺寸 %s，應為 (1536, 1024)" % (im.size,)
    亮 = ImageStat.Stat(im.convert("L")).mean[0]
    if 亮 < 20 or 亮 > 250:
        return False, "整張幾乎全黑或全白（平均亮度 %.1f）" % 亮
    return True, "%.1f MB／平均亮度 %.0f" % (大小 / 1024 / 1024, 亮)


def 生一張(領域, 序, 名, 畫面):
    os.makedirs(OUT, exist_ok=True)
    n = 檔名(領域, 序)
    前 = set(os.listdir(OUT))
    cmd = [sys.executable, DRAW, 提示詞(畫面),
           "--size", "1536x1024", "--quality", "low", "--n", "1",
           "--name", n, "--outdir", OUT]
    print("── %s 第 %d 單元　%s ──" % (領域, 序, 名))
    if subprocess.run(cmd).returncode != 0:
        print("❌ draw.py 回傳非 0")
        return False
    新 = [f for f in os.listdir(OUT) if f not in 前 and f.startswith(n)]
    if not 新:
        print("❌ draw.py 說成功，但沒有新檔案")
        return False
    路徑 = os.path.join(OUT, sorted(新)[-1])
    好, 說明 = _驗出圖(路徑)
    if not 好:
        os.remove(路徑)
        print("❌ 出圖不合格，已刪除：%s" % 說明)
        return False
    print("   ✅ %s %s" % (n, 說明))
    return True


def main():
    args = sys.argv[1:]
    if not args:
        raise SystemExit(__doc__)
    if args[0] == "--list":
        for 領域, 序, 名, 畫面 in 封面:
            print("【%s 第 %d 單元　%s】→ %s\n%s\n" % (領域, 序, 名, 檔名(領域, 序), 提示詞(畫面)))
        print("共 %d 張" % len(封面))
        return

    領域 = args[0]
    指定 = {int(a) for a in args[1:] if a.isdigit()}
    目標 = [c for c in 封面 if c[0] == 領域 and (not 指定 or c[1] in 指定)]
    assert 目標, "🛑 找不到符合的封面（領域 %s，指定 %s）" % (領域, 指定 or "全部")
    print("要生 %d 張" % len(目標))
    成功 = sum(1 for c in 目標 if 生一張(*c))
    print("\n完成 %d／%d 張，輸出在 %s" % (成功, len(目標), OUT))
    print("🛑 接下來要逐張開圖確認（畫面對不對題、有沒有跑出文字），再跑 套用封面.py。")


if __name__ == "__main__":
    main()
